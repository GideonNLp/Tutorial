const plural = new Intl.PluralRules('ro');

/** „1 zi”, „5 zile”, „20 de zile”. */
function count(n: number, one: string, few: string, other: string): string {
  const form = plural.select(n);
  return `${n} ${form === 'one' ? one : form === 'few' ? few : other}`;
}

